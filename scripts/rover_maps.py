"""
Writes packages/code/space/rover_maps.cpp, the maps rover.yaml draws the rovers' tracks on: the CTX mosaic around
each one's crater, 320x240, north up, centred and scaled as rover.h's ROVERS has them. The finest detail is damped
so the track stands out and the JPEG's bytes go further. Each map is 16 greys, picked for it by Lloyd-Max, two pixels
a byte, and its greys tinted as Mars.
    python3 scripts/rover_maps.py CACHE_DIR   (Esri's tiles of the mosaic are kept there)
CTX mosaic: NASA/JPL-Caltech/MSSS, the Murray Lab at Caltech.
"""

import math
import os
import sys
import urllib.request

from PIL import Image, ImageFilter

W, H = 320, 240
TILES = "https://astro.arcgis.com/arcgis/rest/services/OnMars/CTX/MapServer/tile"
LEVEL = 10  # about 20 m a pixel, 180 / 2^LEVEL degrees a 512 px tile
M_PER_DEG = 3396190 * math.pi / 180
# name, the map's middle (east longitude, latitude) and metres a pixel, as rover.h's ROVERS
ROVERS = [("perseverance", 77.338, 18.47, 46), ("curiosity", 137.35, -4.712, 70)]
# Mars from dark to light: umber, butterscotch, pale sand, its tones pulled in so the marks stand out
RAMP = [(25, 16, 15), (79, 48, 34), (141, 92, 62), (189, 154, 118), (205, 187, 164)]
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "packages", "code", "space", "rover_maps.cpp")


def tile(cache, row, col):
    path = os.path.join(cache, f"{LEVEL}_{row}_{col}")
    if not os.path.exists(path):
        req = urllib.request.Request(
            f"{TILES}/{LEVEL}/{row}/{col}", headers={"User-Agent": "rover_maps.py"}
        )
        with urllib.request.urlopen(req, timeout=60) as r, open(path, "wb") as f:
            f.write(r.read())
    return Image.open(path).convert("L")


def level(img, lo_pct=1, hi_pct=99.5):
    """Stretches the 1st to the 99.5th percentile to 0..255"""
    hist, n = img.histogram(), img.width * img.height
    acc, lo, hi = 0, 0, 255
    for v, c in enumerate(hist):
        if acc < n * lo_pct / 100 <= acc + c:
            lo = v
        if acc < n * hi_pct / 100 <= acc + c:
            hi = v
        acc += c
    k = 255 / max(1, hi - lo)
    return img.point(lambda v: max(0, min(255, round((v - lo) * k))))


def view(cache, lon, lat, mpp):
    deg = 180 / 2**LEVEL
    res = deg / 512
    dlat = mpp / M_PER_DEG
    dlon = dlat / math.cos(math.radians(lat))
    west, east = lon - W / 2 * dlon, lon + W / 2 * dlon
    north, south = lat + H / 2 * dlat, lat - H / 2 * dlat
    cols = range(math.floor((west + 180) / deg), math.floor((east + 180) / deg) + 1)
    rows = range(math.floor((90 - north) / deg), math.floor((90 - south) / deg) + 1)
    big = Image.new("L", (512 * len(cols), 512 * len(rows)))
    for i, r in enumerate(rows):
        for j, c in enumerate(cols):
            big.paste(tile(cache, r, c), (512 * j, 512 * i))
    lon0, lat0 = cols[0] * deg - 180, 90 - rows[0] * deg
    box = (
        (west - lon0) / res,
        (lat0 - north) / res,
        (east - lon0) / res,
        (lat0 - south) / res,
    )
    img = level(big.resize((W, H), Image.LANCZOS, box=box))
    return Image.blend(img.filter(ImageFilter.GaussianBlur(1.6)), img, 0.55)


def greys(hist, n=16):
    """n greys for hist, each the mean of the ones nearest it (Lloyd-Max)"""
    lv = [(i + 0.5) * 256 / n for i in range(n)]
    for _ in range(60):
        edges = [0] + [(lv[i] + lv[i + 1]) / 2 for i in range(n - 1)] + [256]
        for i in range(n):
            vs = range(math.ceil(edges[i]), math.ceil(edges[i + 1]))
            c = sum(hist[v] for v in vs)
            if c:
                lv[i] = sum(hist[v] * v for v in vs) / c
    return [round(v) for v in lv]


def tint(v):
    """Grey v as Mars, 0xRRGGBB"""
    k = v * 4
    i = min(k // 255, 3)
    f = (k - i * 255) / 255
    rgb = [round(RAMP[i][c] + (RAMP[i + 1][c] - RAMP[i][c]) * f) for c in range(3)]
    return rgb[0] << 16 | rgb[1] << 8 | rgb[2]


def lines(items):
    """The items as many to a line as fit in 120 characters"""
    line = "       "
    for item in items:
        if len(line) + len(item) + 2 > 120:
            yield line
            line = "       "
        line += f" {item},"
    yield line


def main():
    cache = sys.argv[1]
    os.makedirs(cache, exist_ok=True)
    out = [
        "// Generated by scripts/rover_maps.py from the CTX mosaic (NASA/JPL-Caltech/MSSS, the Murray Lab at Caltech).",
        "// Don't edit.",
        '#include "rover_maps.h"',
        "",
        "namespace flexit::panel::space::rover {",
        "",
        "// clang-format off: tables a line full",
    ]
    for name, lon, lat, mpp in ROVERS:
        img = view(cache, lon, lat, mpp)
        lv = greys(img.histogram())
        near = [min(range(len(lv)), key=lambda i: abs(lv[i] - v)) for v in range(256)]
        px = [near[v] for v in img.tobytes()]
        out.append(f"const Mosaic {name}_mosaic = {{")
        out.append("    {")
        out += lines(f"0x{tint(v):06X}" for v in lv)
        out.append("    },")
        out.append("    {")
        out += lines(str(px[i] << 4 | px[i + 1]) for i in range(0, len(px), 2))
        out.append("    },")
        out.append("};")
    out.append("// clang-format on")
    out.append("")
    out.append("}  // namespace flexit::panel::space::rover")
    with open(OUT, "w") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
