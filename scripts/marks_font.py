"""
Writes packages/code/marks/marks_font.cpp: Noto Sans's glyphs at the sizes marks.h draws text in, 4 bits of
coverage a pixel. Each is drawn at 4x and averaged down, as the panel's own text is.
    python3 scripts/marks_font.py [NOTO_DIR]   (default /usr/share/fonts/noto)
Noto Sans is under the SIL Open Font License 1.1.
"""

import os
import sys

from PIL import Image, ImageDraw, ImageFont

SS = 4
TEXT = "".join(chr(c) for c in range(32, 127)) + "°·–−×½æøåÆØÅéüãíóúçñ"
CAPS = "".join(c for c in TEXT if not c.islower()) + "ÆØÅ"
FIGURES = "0123456789 .,:−-+%°"
# marks.h's faces, in the order of its Face enum: name, weight, size in px, glyphs
FACES = [
    ("CAPS", "Bold", 6.5, CAPS),
    ("SMALL", "Regular", 7.5, TEXT),
    ("LABEL", "Medium", 7, TEXT),
    ("TEXT", "Regular", 9, TEXT),
    ("TITLE", "Medium", 12.5, TEXT),
    ("BIG", "Medium", 15, TEXT),
    ("HUGE", "Medium", 20, FIGURES),
]
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "packages", "code", "marks", "marks_font.cpp")


def lines(items):
    """The items as many to a line as fit in 120 characters"""
    line = "   "
    for item in items:
        if len(line) + len(item) + 2 > 120:
            yield line
            line = "   "
        line += f" {item},"
    yield line


def glyph(font, ch):
    """ch's coverage at 1x as rows of 0..15, where its top left is from the pen on the baseline, and its advance"""
    asc, desc = font.getmetrics()
    pad = 2 * SS
    w = int(font.getlength(ch)) + 4 * pad
    im = Image.new("L", (w, asc + desc + 2 * pad))
    ImageDraw.Draw(im).text((pad, pad + asc), ch, font=font, fill=255, anchor="ls")
    box = im.getbbox()
    adv = font.getlength(ch) / SS
    if not box:
        return 0, 0, [], adv
    # out to the 4x grid the pen is on, so the 1x pixels line up with it
    x0 = pad + (box[0] - pad) // SS * SS
    y0 = pad + asc + (box[1] - pad - asc) // SS * SS
    x1 = x0 + -(-(box[2] - x0) // SS) * SS
    y1 = y0 + -(-(box[3] - y0) // SS) * SS
    small = im.crop((x0, y0, x1, y1)).reduce(SS)
    rows = [
        [(small.getpixel((x, y)) * 15 + 127) // 255 for x in range(small.width)]
        for y in range(small.height)
    ]
    return (x0 - pad) // SS, (y0 - pad - asc) // SS, rows, adv


def main():
    noto = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/noto"
    out = [
        "// Generated by scripts/marks_font.py from Noto Sans (SIL Open Font License 1.1). Don't edit.",
        '#include "marks_font.h"',
        "",
        "namespace flexit::panel::marks {",
        "",
        "// clang-format off: tables a line full",
    ]
    faces, charsets = [], {}
    for name, weight, size, chars in FACES:
        font = ImageFont.truetype(
            os.path.join(noto, f"NotoSans-{weight}.ttf"), round(size * SS)
        )
        codes = sorted({ord(ch) for ch in chars})
        # the faces with the same characters share their codes
        if tuple(codes) not in charsets:
            charsets[tuple(codes)] = f"{name.lower()}_codes"
            out.append(f"static const uint16_t {name.lower()}_codes[] = {{")
            out += lines(str(c) for c in codes)
            out.append("};")
        data, glyphs = [], []
        for code in codes:
            x, y, rows, adv = glyph(font, chr(code))
            at = len(data)
            assert at < 65536
            nib = [v for r in rows for v in r]
            nib += [0] * (len(nib) & 1)
            data += [nib[i] << 4 | nib[i + 1] for i in range(0, len(nib), 2)]
            w = len(rows[0]) if rows else 0
            glyphs.append(f"{{{at}, {round(adv * 16)}, {x}, {y}, {w}, {len(rows)}}}")
        asc, desc = font.getmetrics()
        lo = name.lower()
        out.append(f"static const Glyph {lo}_glyphs[] = {{")
        out += lines(glyphs)
        out.append("};")
        out.append(f"static const uint8_t {lo}_data[] = {{")
        out += lines(str(b) for b in data)
        out.append("};")
        faces.append(
            f"    {{{charsets[tuple(codes)]}, {lo}_glyphs, {len(glyphs)}, {lo}_data, {round(asc / SS)}, "
            f"{round((asc + desc) / SS)}, {float(size)}f}},  // {weight} {size} px"
        )
        print(f"{name}: {len(glyphs)} glyphs, {len(data)} bytes", file=sys.stderr)
    out.append("")
    out.append("const Face FACES[] = {")
    out += faces
    out.append("};")
    out.append("// clang-format on")
    out.append("")
    out.append("}  // namespace flexit::panel::marks")
    with open(OUT, "w") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
